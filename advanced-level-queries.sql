--5. Calculate the cumulative sum of likes for tracks ordered by the number of views, using window functions.
SELECT 
    Track,
    Artist,
    Views,
    Likes,
    SUM(Likes) OVER (
        PARTITION BY Artist 
        ORDER BY Views
    ) AS CumulativeLikes
FROM spotify
ORDER BY Artist, Views;

-- Answer: 20,594 songs 

