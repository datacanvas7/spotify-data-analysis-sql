-- 1.Find the top 3 most-viewed tracks for each artist using window functions.
WITH TrackViews AS (
    SELECT
        Artist,
        Track,
        SUM(Views) AS TotalViews
    FROM spotify
    GROUP BY
        Artist, Track
),
RankedTracks AS (
    SELECT
        Artist,
        Track,
        TotalViews,
        ROW_NUMBER() OVER (
            PARTITION BY Artist
            ORDER BY TotalViews DESC
        ) AS SongRank    -- this is generated by SQL, not from your table
    FROM TrackViews
)
SELECT
    Artist,
    Track,
    TotalViews,
    SongRank
FROM RankedTracks
WHERE SongRank <= 3
ORDER BY Artist, SongRank   

-- Answer: 6,214 total songs as top 3 songs for each artist

